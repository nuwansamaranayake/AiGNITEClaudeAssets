<#
.SYNOPSIS
  Wires Stripe subscriptions and the daily quota check into a scaffolded project.
.PARAMETER ProjectDir
  Path to the Expo project root.
.PARAMETER McpSlug
  AiGNITE MCP slug to look up the default price point.
.PARAMETER MonthlyPrice
  Override monthly price in USD. Defaults from the per-MCP table.
.PARAMETER DryRun
  Print the planned writes without applying them.
#>

[CmdletBinding()]
param(
  [Parameter(Mandatory=$true)][string]$ProjectDir,
  [Parameter(Mandatory=$true)][string]$McpSlug,
  [double]$MonthlyPrice = 0,
  [switch]$DryRun
)

$ErrorActionPreference = "Stop"

$prices = @{
  "beacon-gom"   = 9.99
  "regscope"     = 14.99
  "recallwatch"  = 7.99
  "floodpulse"   = 4.99
  "airshield"    = 4.99
  "cosmic-nexus" = 19.99
}

if ($MonthlyPrice -le 0) {
  if ($prices.ContainsKey($McpSlug)) {
    $MonthlyPrice = $prices[$McpSlug]
  } else {
    throw "Unknown MCP slug '$McpSlug' and no MonthlyPrice override given."
  }
}

Write-Host "--- Wire subscriptions ---"
Write-Host "Project:      $ProjectDir"
Write-Host "Slug:         $McpSlug"
Write-Host "Monthly:      `$$MonthlyPrice"

$skillRoot = Split-Path -Parent $PSScriptRoot
$gateTemplate = Get-Content -Raw (Join-Path $skillRoot "assets\templates\subscription-gate.tsx.template")

$projName = (Get-Item $ProjectDir).Name
$gateRendered = $gateTemplate `
  -replace "\{\{PROJECT_NAME\}\}", $projName `
  -replace "\{\{MONTHLY_PRICE\}\}", $MonthlyPrice `
  -replace "\{\{SLUG\}\}", $McpSlug

$gatePath = Join-Path $ProjectDir "components\SubscriptionGate.tsx"
$formTemplate = Get-Content -Raw (Join-Path $skillRoot "assets\templates\mcp-tool-form.tsx.template")
$formPath = Join-Path $ProjectDir "components\McpToolForm.tsx"

$migrationPath = Join-Path $ProjectDir "supabase\migrations\0002_quota_and_subs.sql"
$migrationSql = @"
-- Quota and subscription tables for $projName
-- Generated by mcp-to-mobile wire-subscriptions.ps1

create table if not exists query_log (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  tool_name text not null,
  used_on date not null default current_date,
  created_at timestamptz default now()
);
alter table query_log enable row level security;
create policy "own_log" on query_log for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create index if not exists idx_query_log_user_day on query_log(user_id, used_on);

create or replace function check_quota(p_user uuid)
returns int
language sql
security definer
as `$`$
  select count(*)::int from query_log
  where user_id = p_user and used_on = current_date;
`$`$;
grant execute on function check_quota(uuid) to authenticated;

create table if not exists device_tokens (
  user_id uuid not null references auth.users(id) on delete cascade,
  token text not null,
  platform text not null check (platform in ('ios','android','web')),
  updated_at timestamptz default now(),
  primary key (user_id, token)
);
alter table device_tokens enable row level security;
create policy "own_token" on device_tokens for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
"@

if ($DryRun) {
  Write-Host "DRY  would write $gatePath"
  Write-Host "DRY  would write $formPath"
  Write-Host "DRY  would write $migrationPath"
  exit 0
}

New-Item -ItemType Directory -Path (Split-Path $gatePath) -Force | Out-Null
Set-Content -LiteralPath $gatePath -Value $gateRendered -Encoding utf8
Write-Host "WROTE $gatePath"

Set-Content -LiteralPath $formPath -Value $formTemplate -Encoding utf8
Write-Host "WROTE $formPath"

New-Item -ItemType Directory -Path (Split-Path $migrationPath) -Force | Out-Null
Set-Content -LiteralPath $migrationPath -Value $migrationSql -Encoding utf8
Write-Host "WROTE $migrationPath"

Write-Host ""
Write-Host "Subscriptions wired. Run supabase-bootstrap to apply the new migration."
Write-Host "Then create the Stripe product in dashboard with price `$$MonthlyPrice/month."
